// YouTube 字幕リーダー用のローカルサーバー（依存パッケージなし / Node.js 18 以上）
//   起動: node server.js  →  http://localhost:3000
// - 静的ファイル (index.html, app.js, style.css) を配信
// - GET /api/transcript?v=<videoId> で YouTube の字幕を取得して JSON で返す
//   （ブラウザから直接 YouTube の字幕を取ると CORS で弾かれるため、サーバー経由にしている）

const http = require("http");
const fs = require("fs");
const path = require("path");

const PORT = process.env.PORT || 3000;
const ROOT = __dirname;
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml",
};

function decodeEntities(s) {
  return s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

// 字幕 XML を [{start, dur, text}] に変換（旧形式 <text> と srv3 形式 <p> の両方に対応）
function parseCaptionXml(xml) {
  const segs = [];
  let m;
  const textRe = /<text start="([\d.]+)"(?: dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/g;
  while ((m = textRe.exec(xml))) {
    segs.push({ start: +m[1], dur: +(m[2] || 0), text: decodeEntities(decodeEntities(m[3])) });
  }
  if (segs.length) return segs;
  const pRe = /<p t="(\d+)"(?: d="(\d+)")?[^>]*>([\s\S]*?)<\/p>/g;
  while ((m = pRe.exec(xml))) {
    const text = decodeEntities(m[3].replace(/<[^>]+>/g, ""));
    if (text.trim()) segs.push({ start: +m[1] / 1000, dur: +(m[2] || 0) / 1000, text });
  }
  return segs;
}

// 英語の手動字幕 > 英語の自動生成字幕 > その他 の優先順で選ぶ
function pickTrack(tracks) {
  const isEn = (t) => /^en(\b|-)/i.test(t.languageCode);
  return (
    tracks.find((t) => isEn(t) && t.kind !== "asr") ||
    tracks.find((t) => isEn(t)) ||
    tracks[0]
  );
}

async function fetchPlayerResponse(videoId) {
  const watch = await fetch(`https://www.youtube.com/watch?v=${videoId}&hl=en`, {
    headers: { "User-Agent": UA, "Accept-Language": "en-US,en;q=0.9", Cookie: "CONSENT=YES+1" },
  });
  const html = await watch.text();
  const title = (html.match(/<meta name="title" content="([^"]*)"/) || [])[1];
  const apiKey = (html.match(/"INNERTUBE_API_KEY":"([^"]+)"/) || [])[1];

  // 1) InnerTube API（ANDROID クライアント）: 取得できる字幕 URL が最も安定している
  if (apiKey) {
    try {
      const res = await fetch(`https://www.youtube.com/youtubei/v1/player?key=${apiKey}`, {
        method: "POST",
        headers: { "Content-Type": "application/json", "User-Agent": UA },
        body: JSON.stringify({
          context: { client: { clientName: "ANDROID", clientVersion: "20.10.38" } },
          videoId,
        }),
      });
      const data = await res.json();
      if (data?.captions) return { data, title };
    } catch (_) {
      /* 下のフォールバックへ */
    }
  }

  // 2) 視聴ページに埋め込まれた ytInitialPlayerResponse
  const m = html.match(/ytInitialPlayerResponse\s*=\s*(\{.+?\})\s*;\s*(?:var\s|<\/script>)/s);
  if (m) {
    try {
      return { data: JSON.parse(m[1]), title };
    } catch (_) {}
  }
  return { data: null, title };
}

async function getTranscript(videoId) {
  const { data, title } = await fetchPlayerResponse(videoId);
  if (!data) throw new Error("YouTube から動画情報を取得できませんでした");
  const tracks = data?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
  if (!tracks.length) {
    const status = data?.playabilityStatus?.status;
    throw new Error(
      status && status !== "OK"
        ? `動画を再生できませんでした (${status})`
        : "この動画には字幕がありません"
    );
  }
  const track = pickTrack(tracks);
  const url = track.baseUrl.replace(/&fmt=[^&]*/, "");
  const xml = await (await fetch(url, { headers: { "User-Agent": UA } })).text();
  const segments = parseCaptionXml(xml);
  if (!segments.length) throw new Error("字幕の取得に失敗しました（空のデータ）");
  return {
    videoId,
    title: data?.videoDetails?.title || (title && decodeEntities(title)) || videoId,
    author: data?.videoDetails?.author || "",
    language: track.languageCode,
    autoGenerated: track.kind === "asr",
    segments,
  };
}

function sendJson(res, status, obj) {
  res.writeHead(status, { "Content-Type": MIME[".json"], "Access-Control-Allow-Origin": "*" });
  res.end(JSON.stringify(obj));
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);

  if (url.pathname === "/api/transcript") {
    const v = url.searchParams.get("v") || "";
    if (!/^[\w-]{11}$/.test(v)) return sendJson(res, 400, { error: "動画IDが正しくありません" });
    try {
      sendJson(res, 200, await getTranscript(v));
    } catch (e) {
      sendJson(res, 502, { error: e.message || String(e) });
    }
    return;
  }

  const rel = url.pathname === "/" ? "index.html" : decodeURIComponent(url.pathname).slice(1);
  const file = path.join(ROOT, rel);
  if (!file.startsWith(ROOT + path.sep)) {
    res.writeHead(403);
    return res.end();
  }
  fs.readFile(file, (err, buf) => {
    if (err) {
      res.writeHead(404);
      return res.end("Not found");
    }
    res.writeHead(200, { "Content-Type": MIME[path.extname(file)] || "application/octet-stream" });
    res.end(buf);
  });
});

if (require.main === module) {
  server.listen(PORT, () => console.log(`YouTube 字幕リーダー: http://localhost:${PORT}`));
}

module.exports = { parseCaptionXml, pickTrack };
